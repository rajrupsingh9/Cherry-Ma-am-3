// KaTeX Safe Render Helper for pure formulas & math snippets
const renderKatex = (latex: string, displayMode: boolean = false): string => {
  if (!latex) return "";
  try {
    let clean = latex.trim();
    // Strip redundant leading/trailing dollar signs if present
    clean = clean.replace(/^\$\$([\s\S]*)\$\$$/, "$1").replace(/^\$([\s\S]*)\$$/, "$1").trim();

    // Check if the input is purely plain text (English words, Devanagari/Hindi) without math operators
    const hasMathSymbols = /[\\_\^=+\-<>/*⇌→↔Δ°\d\(\)\[\]\{\}]/.test(clean);
    const hasSpaces = clean.includes(" ");
    const isPureWords = hasSpaces && !hasMathSymbols && /^[a-zA-Z\u0900-\u097F\s,.:;'!?()-]+$/.test(clean);

    if (isPureWords) {
      // Return clean typography to prevent KaTeX from collapsing spaces into multiplied italic math letters
      return `<span class="font-sans font-medium text-slate-800">${clean}</span>`;
    }

    // Normalize escaped backslashes without breaking LaTeX formatting
    clean = clean.replace(/\\\\/g, "\\");
    // Normalize arrow representations and symbols commonly generated by AI
    clean = clean
      .replace(/<=>|<==>|⇌/g, "\\rightleftharpoons ")
      .replace(/->|➔|→/g, "\\rightarrow ")
      .replace(/<->|↔/g, "\\leftrightarrow ")
      .replace(/Δ/g, "\\Delta ")
      .replace(/°/g, "^\\circ");

    // For very long chemical/math equations, wrap with responsive breakable layout
    return katex.renderToString(clean, {
      displayMode,
      throwOnError: false,
      trust: true,
      strict: false,
    });
  } catch (e) {
    // If KaTeX fails, sanitize the string so no raw brackets or code leak
    return latex.replace(/[{}]/g, "");
  }
};

// Dynamic font sizing utility to prevent formula and math overflows in compact infographic cards
const getFormulaFontSizeClass = (formula: string, baseTier: "sm" | "md" | "lg" = "md"): string => {
  if (!formula) return "text-xs";
  // Strip common LaTeX commands to estimate visual character length
  const cleanLen = formula
    .replace(/\\[a-zA-Z]+/g, "")
    .replace(/[{}\^_\$]/g, "")
    .trim().length;

  if (baseTier === "lg") {
    if (cleanLen > 40) return "text-[10px] leading-tight";
    if (cleanLen > 24) return "text-[11.5px] leading-tight";
    return "text-xs";
  }

  if (baseTier === "sm") {
    if (cleanLen > 30) return "text-[8.5px] leading-tight";
    if (cleanLen > 18) return "text-[9.5px] leading-tight";
    return "text-[10.5px]";
  }

  // "md" Tier (Default for Case Studies 1-4)
  if (cleanLen > 45) return "text-[8.5px] leading-tight";
  if (cleanLen > 28) return "text-[9.5px] leading-tight";
  if (cleanLen > 16) return "text-[10.5px] leading-tight";
  return "text-xs";
};

// KaTeX Safe Parser for mixed text containing prose + LaTeX ($...$ or inline math/subscripts)
const renderTextWithKatex = (text: string): string => {
  if (!text) return "";
  try {
    let processed = text;

    // 1. Strip raw AI markdown formatting or file hash artifacts
    processed = processed
      .replace(/file_00000000[0-9a-fA-F_-]+(\.png)?/gi, "")
      .replace(/\*\*(.*?)\*\*/g, "<strong>$1</strong>")
      .replace(/\*(.*?)\*/g, "<em>$1</em>");

    // 2. If string has $$...$$ (display math blocks)
    if (processed.includes("$$")) {
      processed = processed.replace(/\$\$([\s\S]*?)\$\$/g, (_, latex) => {
        try {
          return `<span class="inline-block my-0.5">${renderKatex(latex, true)}</span>`;
        } catch {
          return latex;
        }
      });
    }

    // 3. If string has $...$ (inline math)
    if (processed.includes("$")) {
      processed = processed.replace(/\$([^\$]+)\$/g, (_, latex) => {
        try {
          return renderKatex(latex, false);
        } catch {
          return latex;
        }
      });
    }

    // 4. Handle inline chemical/physical subscripts & superscripts without dollar signs
    // e.g. NH_3, H_2O, CO_2, Fe^{2+}, SO_4^{2-}, v_A, v_B, x_1, x_2, R_{eq}, T_1, P_1, \Delta H
    if (/\\Delta\s*[A-Za-z0-9]/.test(processed)) {
      processed = processed.replace(/\\Delta\s*([A-Za-z0-9]+)/g, (_, sym) => renderKatex(`\\Delta ${sym}`, false));
    }

    if (/([A-Za-z0-9\(\)]+)_\{([0-9a-zA-Z+-]+)\}/.test(processed) || /([A-Za-z0-9\(\)]+)\^\{([0-9a-zA-Z+-]+)\}/.test(processed)) {
      processed = processed
        .replace(/([A-Za-z0-9\(\)]+)_\{([0-9a-zA-Z+-]+)\}/g, (_, base, sub) => renderKatex(`${base}_{${sub}}`, false))
        .replace(/([A-Za-z0-9\(\)]+)\^\{([0-9a-zA-Z+-]+)\}/g, (_, base, sup) => renderKatex(`${base}^{${sup}}`, false));
    }

    // Single character subscripts like NH_3, CO_2, H_2, O_2, v_A, v_B, x_1, x_2
    if (/\b([A-Z][a-z]?|\bv)_([0-9]|[A-Za-z])\b/.test(processed)) {
      processed = processed.replace(/\b([A-Z][a-z]?|\bv)_([0-9]|[A-Za-z])\b/g, (_, base, sub) => renderKatex(`${base}_{${sub}}`, false));
    }

    // 5. Handle unbracketed chemical reactions or arrows in text
    if (processed.includes("\\rightleftharpoons") || processed.includes("\\rightarrow") || processed.includes("⇌") || processed.includes("➔")) {
      // If it looks like a complete equation, parse equation parts
      if (!processed.includes("<span") && !processed.includes("<strong>")) {
        return renderKatex(processed, false);
      }
    }

    // 6. Handle stray \text{...} wrappers in text
    processed = processed.replace(/\\text\{([^{}]*)\}/g, "$1");

    // 7. Clean orphaned trailing braces or formatting artifacts
    processed = processed.replace(/\\\\/g, "\\").replace(/\{(\d+)\}/g, "$1");

    return processed;
  } catch (e) {
    return text;
  }
};

